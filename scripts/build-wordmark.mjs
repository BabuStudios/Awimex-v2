/**
 * Builds public/brand/awimex-wordmark.svg — the procedural stand-in for the
 * official logo (⚑ MISSING ASSET: only white PNGs exist). Each letter is an
 * outlined path from Archivo Expanded ExtraBold, so DrawSVG can stroke it.
 *
 * Also writes src/overlay/wordmark.generated.ts for inline use (intro, nav).
 *
 * Dev-time only: fetches the font once from Google Fonts. Nothing is fetched
 * at runtime. Replace the output file with the official SVG when supplied;
 * keep one <path class="letter"> per glyph for the intro to draw.
 */

import { writeFile, mkdir } from "node:fs/promises";
import opentype from "opentype.js";

const WORD = "AWIMEX";
const CSS_URL = `https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@125,800&text=${WORD}`;
const OUT = new URL("../public/brand/awimex-wordmark.svg", import.meta.url);

const css = await (await fetch(CSS_URL)).text();
const src = css.match(/url\((https:[^)]+)\)/)?.[1];
if (!src) throw new Error("Could not resolve the Archivo font URL from Google Fonts CSS.");
const font = opentype.parse(await (await fetch(src)).arrayBuffer());

/** opentype.js's own toPathData() writes NaN for float noise like 322.00000000000006. */
const n = (v) => String(Math.round(v * 100) / 100);
function pathData(commands) {
  return commands
    .map((c) => {
      switch (c.type) {
        case "M": case "L": return `${c.type}${n(c.x)} ${n(c.y)}`;
        case "Q": return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case "C": return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        case "Z": return "Z";
        default: throw new Error(`Unknown path command ${c.type}`);
      }
    })
    .join("");
}

const size = 100;
const tracking = 6;
let x = 0;
const paths = [];
for (const ch of WORD) {
  const glyph = font.charToGlyph(ch);
  const d = pathData(glyph.getPath(x, size, size).commands);
  if (d.includes("NaN")) throw new Error(`Glyph "${ch}" produced an invalid path.`);
  paths.push(d);
  x += (glyph.advanceWidth / font.unitsPerEm) * size + tracking;
}
const width = Math.ceil(x - tracking);
const top = size - Math.ceil((font.tables.os2?.sCapHeight ?? font.ascender * 0.72) / font.unitsPerEm * size);
const height = size - top;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 ${top} ${width} ${height}" width="${width}" height="${height}" role="img" aria-label="Awimex">
${paths.map((d) => `  <path class="letter" d="${d}"/>`).join("\n")}
</svg>
`;

await mkdir(new URL("../public/brand/", import.meta.url), { recursive: true });
await writeFile(OUT, svg);
await writeFile(
  new URL("../src/overlay/wordmark.generated.ts", import.meta.url),
  `// Generated by scripts/build-wordmark.mjs — do not edit.\nexport const wordmark = ${JSON.stringify({ viewBox: `0 ${top} ${width} ${height}`, width, height, paths }, null, 2)} as const;\n`,
);
console.log(`wordmark → public/brand/awimex-wordmark.svg (${width}×${height})`);
