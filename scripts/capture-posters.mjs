/**
 * Renders one poster per scene from the live 3D world.
 *
 *   npm run build && npm start            # in one terminal
 *   npm run posters [-- http://localhost:3000]
 *
 * Writes public/posters/poster-<id>.avif (STATIC tier + LCP-safe backdrop),
 * public/posters/poster-hero.jpg (Open Graph image source) and regenerates
 * src/static/posters.generated.ts.
 *
 * ⚑ Shoot the final set on a machine with a real GPU. A software renderer
 * (CI, cloud containers) produces darker, noisier frames.
 *
 * Browser: set CHROMIUM_PATH, or let playwright-core find an installed
 * Chromium.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { chromium } from "playwright-core";
import sharp from "sharp";

const BASE = process.argv[2] ?? "http://localhost:3000";
const OUT = new URL("../public/posters/", import.meta.url);
const SIZE = { width: 1600, height: 1000 };

/** Track position (vh) per scene — mid-hold, where each scene reads best. Mirrors timeline.ts. */
const SHOTS = [
  { id: "hero", file: "poster-hero", vh: 60 },
  { id: "omOss", file: "poster-om-oss", vh: 190 },
  { id: "produkter", file: "poster-produkter", vh: 343 },
  { id: "verksamhet", file: "poster-verksamhet", vh: 588 },
  { id: "kontakt", file: "poster-kontakt", vh: 920 },
];

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  args: ["--ignore-gpu-blocklist", "--enable-unsafe-webgpu"],
});
const page = await (await browser.newContext({ viewport: SIZE, deviceScaleFactor: 1 })).newPage();
await page.goto(`${BASE}/?tier=full&capture`, { waitUntil: "load" });
await page.waitForFunction(() => document.querySelector("canvas") !== null, null, { timeout: 60_000 });
// Let shaders compile, the canvas fade in and the hero bar finish igniting.
await page.waitForTimeout(12_000);

await mkdir(OUT, { recursive: true });
const manifest = {};

for (const shot of SHOTS) {
  await page.evaluate((vh) => window.scrollTo(0, (vh / 100) * window.innerHeight), shot.vh);
  await page.waitForTimeout(6_000);
  const png = await page.screenshot({ type: "png" });
  await sharp(png).avif({ quality: 55, effort: 6 }).toFile(new URL(`${shot.file}.avif`, OUT).pathname);
  if (shot.id === "hero") {
    await sharp(png).resize(1200, 630, { fit: "cover", position: "right" }).jpeg({ quality: 82 }).toFile(new URL("poster-hero.jpg", OUT).pathname);
  }
  manifest[shot.id] = { src: `/posters/${shot.file}.avif`, width: SIZE.width, height: SIZE.height };
  console.log(`poster → public/posters/${shot.file}.avif`);
}

await browser.close();

const ts = `// Generated by scripts/capture-posters.mjs — do not edit.
// A scene without a captured poster falls back to its CSS atmosphere.
import type { SceneId } from "@/content/content";

export type Poster = { src: string; width: number; height: number };

export const posters: Record<SceneId, Poster | null> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile(new URL("../src/static/posters.generated.ts", import.meta.url), ts);
console.log("manifest → src/static/posters.generated.ts");
